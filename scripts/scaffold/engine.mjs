// The pruning engine: plans every change in memory, then writes it.
// Nothing here knows about a specific feature: that lives in features.mjs.
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import process from "node:process";

import { FEATURES, conditionalOps, describeProject } from "./features.mjs";

// ---- walking the project -----------------------------------------------------------------

const SKIP_DIRS = new Set([
  "node_modules",
  ".git",
  ".claude",
  ".venv",
  ".next",
  "out",
  "dist",
  "release",
  "__pycache__",
  ".turbo",
  ".pytest_cache",
  ".ruff_cache",
  "coverage",
]);
// Lockfiles are regenerated by the package managers, never edited by hand.
const SKIP_FILES = new Set(["pnpm-lock.yaml", "uv.lock"]);
// These files document the marker syntax, so they contain it on purpose.
const SKIP_PREFIXES = ["scripts/scaffold/", "docs/SCAFFOLD.md"];
const BINARY_EXTENSIONS = new Set([
  ".png",
  ".ico",
  ".icns",
  ".jpg",
  ".jpeg",
  ".gif",
  ".webp",
  ".woff",
  ".woff2",
  ".ttf",
  ".db",
  ".sqlite",
  ".zip",
  ".dmg",
  ".exe",
  ".pdf",
]);

export function isScaffoldFile(rel) {
  return SKIP_PREFIXES.some((prefix) => rel === prefix || rel.startsWith(prefix));
}

/** Every file of the project as a posix path relative to `root`. */
export function listFiles(root) {
  const files = [];
  const visit = (dir) => {
    for (const entry of fs.readdirSync(path.join(root, dir), { withFileTypes: true })) {
      const rel = dir ? `${dir}/${entry.name}` : entry.name;
      if (entry.isDirectory()) {
        if (!SKIP_DIRS.has(entry.name)) visit(rel);
      } else if (entry.isFile() && !SKIP_FILES.has(entry.name)) {
        files.push(rel);
      }
    }
  };
  visit("");
  return files;
}

/** Text of a file, or null for a binary one. */
export function readText(root, rel) {
  if (BINARY_EXTENSIONS.has(path.extname(rel).toLowerCase())) return null;
  const buffer = fs.readFileSync(path.join(root, rel));
  return buffer.includes(0) ? null : buffer.toString("utf8");
}

// ---- markers -----------------------------------------------------------------------------

// One feature, or several separated by commas ("a,b" = when ANY of them is removed).
const NAME = "([a-z][a-z0-9-]*(?:,[a-z][a-z0-9-]*)*)";
// A whole line: `// scaffold:begin x`, `# scaffold:end !x`, `<!-- scaffold:begin x -->`, `{/* ... */}`.
const BLOCK = new RegExp(
  `^\\s*(?:\\/\\/|#|<!--|\\{\\/\\*|\\/\\*)\\s*scaffold:(begin|end)\\s+(!?)${NAME}\\s*(?:-->|\\*\\/\\}|\\*\\/)?\\s*$`,
);
// The end of a code line: `code  // scaffold:line x`. Or anywhere in a Markdown line.
const LINE_PATTERNS = [
  new RegExp(`\\s*<!--\\s*scaffold:line\\s+(!?)${NAME}\\s*-->`),
  new RegExp(`\\s*\\/\\*\\s*scaffold:line\\s+(!?)${NAME}\\s*\\*\\/\\s*$`),
  new RegExp(`\\s*(?:\\/\\/|#)\\s*scaffold:line\\s+(!?)${NAME}\\s*$`),
];
const ANY_MARKER = /scaffold:(begin|end|line)/;

function whereError(file, lineNumber, message) {
  return new Error(`${file}:${lineNumber}: ${message}`);
}

/**
 * Applies the markers of one file. A block (or line) of a removed feature disappears; one of a
 * kept feature loses only its marker. `!x` flips the rule (used for "instead of" variants).
 * Throws on unbalanced, mismatched or unknown markers, so a typo cannot ship silently.
 */
export function processMarkers(text, removed, file) {
  if (!text.includes("scaffold:")) return text;

  const dropsWhen = (negated, name) => {
    const anyRemoved = name.split(",").some((feature) => removed.has(feature));
    return negated ? !anyRemoved : anyRemoved;
  };
  const known = (name, lineNumber) => {
    for (const feature of name.split(",")) {
      if (!FEATURES[feature]) throw whereError(file, lineNumber, `unknown feature "${feature}"`);
    }
  };

  const out = [];
  const stack = [];
  let dropping = 0;
  const lines = text.split("\n");

  lines.forEach((line, index) => {
    const lineNumber = index + 1;
    const block = BLOCK.exec(line);
    if (block) {
      const [, kind, negation, name] = block;
      known(name, lineNumber);
      if (kind === "begin") {
        const drop = dropsWhen(Boolean(negation), name);
        stack.push({ name, negation, drop, lineNumber });
        if (drop) dropping += 1;
      } else {
        const top = stack.pop();
        if (!top || top.name !== name || top.negation !== negation) {
          throw whereError(
            file,
            lineNumber,
            `"end ${negation}${name}" does not match the open block`,
          );
        }
        if (top.drop) dropping -= 1;
      }
      return;
    }

    let current = line;
    let dropLine = false;
    for (const pattern of LINE_PATTERNS) {
      const match = pattern.exec(current);
      if (match) {
        const [, negation, name] = match;
        known(name, lineNumber);
        dropLine = dropsWhen(Boolean(negation), name);
        current = current.replace(pattern, "");
        break;
      }
    }
    if (current === line && ANY_MARKER.test(line)) {
      throw whereError(file, lineNumber, "malformed scaffold marker");
    }
    if (dropping === 0 && !dropLine) out.push(current);
  });

  if (stack.length > 0) {
    const open = stack[stack.length - 1];
    throw whereError(file, open.lineNumber, `block "${open.name}" is never closed`);
  }
  return out.join("\n");
}

// ---- JSON, text and CORS edits ------------------------------------------------------------

function pruneEmptyParents(root, parts) {
  for (let depth = parts.length - 1; depth > 0; depth -= 1) {
    const parent = parts.slice(0, depth).reduce((node, key) => node?.[key], root);
    if (parent && typeof parent === "object" && Object.keys(parent).length === 0) {
      const grand = parts.slice(0, depth - 1).reduce((node, key) => node?.[key], root);
      delete grand[parts[depth - 1]];
    } else {
      break;
    }
  }
}

function deletePath(root, dotted) {
  const parts = dotted.split(".");
  const parent = parts.slice(0, -1).reduce((node, key) => node?.[key], root);
  if (!parent || typeof parent !== "object" || !(parts.at(-1) in parent)) return;
  delete parent[parts.at(-1)];
  pruneEmptyParents(root, parts);
}

function setPath(root, dotted, value) {
  const parts = dotted.split(".");
  let node = root;
  for (const key of parts.slice(0, -1)) {
    node[key] ??= {};
    node = node[key];
  }
  node[parts.at(-1)] = value;
}

function applyJsonOp(data, op) {
  for (const dotted of op.del ?? []) deletePath(data, dotted);
  for (const [dotted, value] of Object.entries(op.set ?? {})) setPath(data, dotted, value);
  if (op.arrayRemove) {
    const { path: dotted, values, dropEmpty } = op.arrayRemove;
    const parts = dotted.split(".");
    const parent = parts.slice(0, -1).reduce((node, key) => node?.[key], data);
    const list = parent?.[parts.at(-1)];
    if (Array.isArray(list)) {
      const next = list.filter((item) => !values.includes(item));
      if (next.length === 0 && dropEmpty) deletePath(data, dotted);
      else parent[parts.at(-1)] = next;
    }
  }
}

const CORS_FILES = [
  "apps/api/.env.development",
  "apps/api/.env.production.example",
  "docker-compose.yml",
];

function stripOrigins(text, origins) {
  return text
    .split("\n")
    .map((line) => {
      if (!line.includes("CORS_ORIGINS")) return line;
      let result = line;
      for (const origin of origins) {
        result = result.replace(`${origin},`, "").replace(`,${origin}`, "").replace(origin, "");
      }
      return result;
    })
    .join("\n");
}

// ---- unused catalog entries ---------------------------------------------------------------

function dependencyNames(pkg) {
  return ["dependencies", "devDependencies", "peerDependencies"].flatMap((group) =>
    Object.entries(pkg[group] ?? {}),
  );
}

function pruneWorkspaceFile(text, surviving) {
  const catalogUsed = new Set();
  const anyUsed = new Set();
  for (const pkg of surviving) {
    for (const [name, spec] of dependencyNames(pkg)) {
      anyUsed.add(name);
      if (spec === "catalog:") catalogUsed.add(name);
    }
  }

  let section = "";
  return text
    .split("\n")
    .filter((line) => {
      if (/^\S/.test(line) && !line.startsWith("#")) section = line.split(":")[0];
      if (section === "catalog") {
        const match = /^ {2}"?([^":\s]+)"?:\s/.exec(line);
        if (match) return catalogUsed.has(match[1]);
      }
      if (section === "minimumReleaseAgeExclude") {
        const match = /^ {2}- (.+)@[^@]+$/.exec(line);
        if (match) return anyUsed.has(match[1]);
      }
      return true;
    })
    .join("\n");
}

// ---- planning ------------------------------------------------------------------------------

function assertSafePath(rel) {
  const normalized = path.posix.normalize(rel);
  if (
    !rel ||
    path.isAbsolute(rel) ||
    normalized.startsWith("..") ||
    normalized === "." ||
    normalized !== rel
  ) {
    throw new Error(`Refusing to touch unsafe path "${rel}"`);
  }
}

const isUnder = (rel, folder) => rel === folder || rel.startsWith(`${folder}/`);

/**
 * Computes everything `apply` will do without touching the disk.
 * Returns { files: Map(path -> new text), deletes: [path], created: [path] }.
 */
export function plan(root, removed) {
  const overlay = new Map();
  const created = new Set();
  const read = (rel) => {
    if (overlay.has(rel)) return overlay.get(rel);
    const full = path.join(root, rel);
    if (!fs.existsSync(full)) throw new Error(`${rel} does not exist but the manifest edits it`);
    return fs.readFileSync(full, "utf8");
  };

  // 1. Markers, in every text file.
  for (const rel of listFiles(root)) {
    if (isScaffoldFile(rel)) continue;
    const text = readText(root, rel);
    if (text === null || !text.includes("scaffold:")) continue;
    const next = processMarkers(text, removed, rel);
    if (next !== text) overlay.set(rel, next);
  }

  // 2. Edits owned by each removed feature.
  const conditional = conditionalOps(removed);
  const ops = { json: [...conditional.json], text: [...conditional.text], write: [], cors: [] };
  const deletes = new Set();
  for (const [name, feature] of Object.entries(FEATURES)) {
    if (!removed.has(name)) continue;
    ops.json.push(...(feature.json ?? []));
    ops.text.push(...(feature.text ?? []));
    ops.write.push(...(feature.write ?? []));
    ops.cors.push(...(feature.cors ?? []));
    for (const rel of feature.delete ?? []) deletes.add(rel);
  }

  for (const rel of deletes) assertSafePath(rel);

  for (const op of ops.write) {
    assertSafePath(op.file);
    overlay.set(op.file, op.content);
    created.add(op.file);
  }
  for (const op of ops.text) {
    const text = read(op.file);
    if (!text.includes(op.from))
      throw new Error(`${op.file}: text edit not found: ${JSON.stringify(op.from)}`);
    overlay.set(op.file, text.split(op.from).join(op.to));
  }
  for (const op of ops.json) {
    const data = JSON.parse(read(op.file));
    const before = JSON.stringify(data);
    applyJsonOp(data, op);
    // Rewrite only what really changed, so untouched files keep their exact formatting.
    if (JSON.stringify(data) !== before) overlay.set(op.file, `${JSON.stringify(data, null, 2)}\n`);
  }
  if (ops.cors.length > 0) {
    for (const rel of CORS_FILES) {
      if (!fs.existsSync(path.join(root, rel))) continue;
      overlay.set(rel, stripOrigins(read(rel), ops.cors));
    }
  }

  // 3. Root package.json description and the pnpm catalog follow what survives.
  const rootPackage = JSON.parse(read("package.json"));
  const description = describeProject(removed);
  if (rootPackage.description !== description) {
    rootPackage.description = description;
    overlay.set("package.json", `${JSON.stringify(rootPackage, null, 2)}\n`);
  }

  const doomed = [...deletes];
  const survives = (rel) => !doomed.some((folder) => isUnder(rel, folder));
  const manifests = listFiles(root)
    .concat([...created])
    .filter((rel) => /^(apps|packages)\/[^/]+\/package\.json$/.test(rel) || rel === "package.json")
    .filter(survives);
  const surviving = [...new Set(manifests)].map((rel) => JSON.parse(read(rel)));
  overlay.set("pnpm-workspace.yaml", pruneWorkspaceFile(read("pnpm-workspace.yaml"), surviving));

  const existing = [...deletes]
    .filter((rel) => fs.existsSync(path.join(root, rel)))
    // A path inside another deleted path needs no line of its own.
    .filter((rel, _, all) => !all.some((other) => other !== rel && isUnder(rel, other)));
  const files = new Map([...overlay].filter(([rel]) => survives(rel)));
  // Keep only what really changes.
  for (const [rel, text] of [...files]) {
    const full = path.join(root, rel);
    if (fs.existsSync(full) && fs.readFileSync(full, "utf8") === text) files.delete(rel);
  }
  return { files, deletes: existing.sort(), created: [...created].filter(survives) };
}

/** Writes a plan to disk. Edits first, deletions last (an edit may sit inside a deleted folder). */
export function apply(root, changes) {
  for (const [rel, text] of changes.files) {
    const full = path.join(root, rel);
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, text);
  }
  for (const rel of changes.deletes) {
    fs.rmSync(path.join(root, rel), { recursive: true, force: true });
    // Do not leave empty folders behind (git would not track them anyway).
    let parent = path.dirname(path.join(root, rel));
    while (parent !== root && fs.existsSync(parent) && fs.readdirSync(parent).length === 0) {
      fs.rmdirSync(parent);
      parent = path.dirname(parent);
    }
  }
}

// ---- finishing: lockfiles and formatting ---------------------------------------------------

const SHELL = process.platform === "win32";

function run(command, args, cwd, log) {
  log(`$ ${command} ${args.join(" ")}`);
  const result = spawnSync(command, args, { cwd, stdio: "inherit", shell: SHELL });
  if (result.status !== 0)
    throw new Error(`"${command} ${args.join(" ")}" exited with ${result.status}`);
}

const PRETTIER_EXTENSIONS = new Set([
  ".md",
  ".json",
  ".ts",
  ".tsx",
  ".js",
  ".mjs",
  ".css",
  ".yml",
  ".yaml",
  ".html",
]);

/** Refreshes both lockfiles and formats what the engine touched. */
export function finish(root, changes, log) {
  run("pnpm", ["install", "--no-frozen-lockfile"], root, log);

  const hasApi = fs.existsSync(path.join(root, "apps", "api", "pyproject.toml"));
  if (hasApi) {
    run("uv", ["lock"], path.join(root, "apps", "api"), log);
    run("uv", ["run", "ruff", "format", "."], path.join(root, "apps", "api"), log);
  }

  const touched = [...changes.files.keys()].filter(
    (rel) => PRETTIER_EXTENSIONS.has(path.extname(rel)) && fs.existsSync(path.join(root, rel)),
  );
  for (let start = 0; start < touched.length; start += 40) {
    run(
      "pnpm",
      ["exec", "prettier", "--write", "--ignore-unknown", ...touched.slice(start, start + 40)],
      root,
      log,
    );
  }
}
